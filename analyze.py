#!/usr/bin/env python3
"""
Turn the sweep CSVs in data/ into results.md (tables) and figures/memory_ledger.png.

Expected files in data/ (any missing optional file is skipped):
  alloc.csv     short prompt (64 tok), n_ctx 128..32768, default settings   [required]
  fill.csv      context ~90% full, n_ctx 512..4096, default settings        [required]
  fa.csv        short prompt, --flash-attn                                   [optional]
  ub128.csv     short prompt, --n-ubatch 128 --n-batch 128                   [optional]
  fill_fa.csv   context ~90% full, --flash-attn                              [optional]
  threads1.csv  short prompt, --threads 1                                    [optional]

Usage:  python3 analyze.py
"""
import math, os
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
DATA, FIG = os.path.join(HERE, "data"), os.path.join(HERE, "figures")
MiB = 1024 * 1024

# ---- Model and board constants (Qwen2.5-0.5B-Instruct Q4_K_M, SL2610) ----
VOCAB = 151936          # n_vocab, from the GGUF / llama.cpp load log
N_HEAD = 14             # query heads
BOARD_RAM_MIB = 1916    # `free -m` total
WEIGHTS_MIB = 462.96    # CPU_Mapped model buffer (read once per decoded token)
# Measured with a numpy copy loop of two 256 MiB float32 arrays (read+write counted):
BW_1CORE_GBS = 3.22     # one process
BW_2CORE_GBS = 2.98     # two processes together (1.48 + 1.50)


def load(name, required=False):
    p = os.path.join(DATA, name)
    if not os.path.exists(p):
        if required:
            raise SystemExit(f"missing {p}")
        return None
    df = pd.read_csv(p)
    df = df[df["status"] == "ok"]
    # one row per n_ctx: mean over repeats, plus spread of VmHWM
    g = df.groupby("n_ctx")
    out = g.mean(numeric_only=True)
    out["vmhwm_spread_mib"] = g["vmhwm_mib"].max() - g["vmhwm_mib"].min()
    out["runs"] = g.size()
    out["flash_attn"] = g["flash_attn_runtime"].first().astype(str)
    return out.reset_index()


def compute_buf_pred(n_ctx, n_ubatch, flash):
    """max(output-score buffer, attention-score buffer + attention mask), in MiB.
    llama.cpp reserves the compute buffer for a worst-case micro-batch in which every
    position produces vocab logits; the attention terms vanish with flash attention."""
    ub = min(n_ubatch, n_ctx)
    logits = ub * VOCAB * 4
    if flash:
        return logits / MiB
    kq = ub * n_ctx * N_HEAD * 4
    mask = ub * n_ctx * 4
    return max(logits, kq + mask) / MiB


def kq_max_mib(prompt_tokens, n_batch=512, pad=256):
    """Largest attention-score matrix built during prefill (f32), MiB."""
    best, done = 0, 0
    while done < prompt_tokens:
        ub = min(n_batch, prompt_tokens - done)
        n_kv = math.ceil((done + ub) / pad) * pad
        best = max(best, ub * n_kv * N_HEAD * 4)
        done += ub
    return best / MiB


def md_table(df, cols, headers, fmt):
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(f(r[c]) for c, f in zip(cols, fmt)) + " |")
    return "\n".join(lines)


i0 = lambda v: f"{int(v):,}"
f1 = lambda v: f"{v:.1f}"
f2 = lambda v: f"{v:.2f}"
f3 = lambda v: f"{v:.3f}"
pc = lambda v: f"{v:+.2f}%"


def main():
    os.makedirs(FIG, exist_ok=True)
    alloc, fill = load("alloc.csv", True), load("fill.csv", True)
    out = ["# Results\n", "_Generated by `analyze.py`. All memory in MiB; values are means over repeats._\n"]

    # ---- 1. KV cache: formula vs runtime --------------------------------
    out.append("## 1. KV cache: predicted vs runtime-reported\n")
    out.append("Prediction: 2 (K,V) x 24 layers x 2 KV heads x 64 head_dim x 2 bytes x n_ctx.\n")
    out.append(md_table(alloc, ["n_ctx", "kv_pred_mib", "kv_buf_reported_mib", "kv_err_pct"],
                        ["n_ctx", "Predicted", "Reported", "Error"], [i0, f2, f2, pc]))

    # ---- 2. The ledger gap: runtime report vs OS peak vs prediction ------
    a = alloc.copy()
    anchor = a.loc[a["n_ctx"].idxmin()]
    a["pred_vmhwm"] = anchor["vmhwm_mib"] + (a["kv_pred_mib"] - anchor["kv_pred_mib"])
    a["pred_err_pct"] = 100 * (a["pred_vmhwm"] - a["vmhwm_mib"]) / a["vmhwm_mib"]
    a["overstate"] = a["runtime_total_mib"] - a["vmhwm_mib"]
    out.append("\n\n## 2. What the runtime reports vs what the OS measures (short prompt)\n")
    out.append(f"Prediction: VmHWM at n_ctx={int(anchor['n_ctx'])} (one anchor run) + extra KV bytes "
               "from the formula. No fitted parameters.\n")
    out.append(md_table(a, ["n_ctx", "runtime_total_mib", "vmhwm_mib", "pred_vmhwm", "pred_err_pct",
                            "overstate", "vmhwm_spread_mib"],
                        ["n_ctx", "llama.cpp total", "OS peak (VmHWM)", "Predicted peak", "Error",
                         "Runtime overstates by", "Spread"],
                        [i0, f1, f1, f1, pc, f1, f2]))

    # ---- 3. Compute buffer: closed form --------------------------------
    rows = []
    for name, ub_default in [("alloc.csv", 512), ("fa.csv", 512), ("ub128.csv", 128)]:
        d = load(name)
        if d is None:
            continue
        for _, r in d.iterrows():
            ub = int(r.get("n_ubatch", ub_default))
            flash = str(r["flash_attn"]).strip() not in ("0", "False", "false", "nan")
            pred = compute_buf_pred(int(r["n_ctx"]), ub, flash)
            rows.append(dict(config=name.replace(".csv", ""), n_ctx=r["n_ctx"], n_ubatch=ub,
                             flash="on" if flash else "off", pred=pred,
                             rep=r["compute_buf_total_mib"], gap=r["compute_buf_total_mib"] - pred))
    cb = pd.DataFrame(rows)
    out.append("\n\n## 3. Compute buffer: closed form vs reported\n")
    out.append(f"Prediction: max(n_ubatch x vocab x 4 B, n_ubatch x n_ctx x heads x 4 B + mask "
               f"n_ubatch x n_ctx x 4 B); attention terms dropped with flash attention. vocab={VOCAB}, heads={N_HEAD}.\n")
    out.append(md_table(cb, ["config", "n_ctx", "n_ubatch", "flash", "pred", "rep", "gap"],
                        ["Config", "n_ctx", "n_ubatch", "Flash attn", "Predicted", "Reported", "Gap"],
                        [str, i0, i0, str, f2, f2, f2]))

    # ---- 4. Full context: memory actually touched ------------------------
    f = fill.copy()
    short_touch = (alloc["peak_anon_sampled_mib"] - alloc["anon_loaded_mib"]).median()
    f["touched"] = f["peak_anon_sampled_mib"] - f["anon_loaded_mib"]
    f["extra"] = f["touched"] - short_touch
    f["kq_max"] = [kq_max_mib(int(p)) for p in f["prompt_tokens"]]
    f["kq15"] = 1.5 * f["kq_max"]
    f["resid"] = f["extra"] - f["kq15"]
    out.append("\n\n## 4. Full context (~90% filled)\n")
    out.append(f"`extra` = anonymous memory touched during inference minus the {short_touch:.1f} MiB a "
               "short prompt touches. The 1.5x column is a tested-and-dropped hypothesis: flash attention "
               "removed about 1x the attention matrix plus mask, not 1.5x (see the flash-attention table below).\n")
    out.append(md_table(f, ["n_ctx", "prompt_tokens", "vmhwm_mib", "extra", "kq_max", "kq15", "resid"],
                        ["n_ctx", "Prompt tok", "VmHWM", "Extra touched", "Attn matrix (max)",
                         "1.5x attn", "Residual"], [i0, i0, f1, f1, f1, f1, f1]))
    ffa = load("fill_fa.csv")
    if ffa is not None:
        ffa["extra"] = ffa["peak_anon_sampled_mib"] - ffa["anon_loaded_mib"] - short_touch
        out.append("\n\nWith flash attention (test of the hypothesis):\n")
        out.append(md_table(ffa, ["n_ctx", "prompt_tokens", "vmhwm_mib", "extra"],
                            ["n_ctx", "Prompt tok", "VmHWM", "Extra touched"], [i0, i0, f1, f1]))

    # ---- 5. Speed and bandwidth -----------------------------------------
    s = pd.concat([alloc.assign(ctx="short prompt"), fill.assign(ctx="~90% full")])
    s["weight_gbs"] = WEIGHTS_MIB * MiB * s["decode_tps"] / 1e9
    t1 = load("threads1.csv")
    if t1 is not None:
        s = pd.concat([s, t1.assign(ctx="short, 1 thread")])
        s["weight_gbs"] = WEIGHTS_MIB * MiB * s["decode_tps"] / 1e9
    s["pct_bw"] = 100 * s["weight_gbs"] / BW_2CORE_GBS
    out.append("\n\n## 5. Speed and memory bandwidth\n")
    ceil_lo = BW_2CORE_GBS * 1e9 / (WEIGHTS_MIB * MiB)
    ceil_hi = BW_1CORE_GBS * 1e9 / (WEIGHTS_MIB * MiB)
    out.append(f"Each decoded token reads all {WEIGHTS_MIB} MiB of weights. Measured copy bandwidth: "
               f"{BW_1CORE_GBS} GB/s (1 core), {BW_2CORE_GBS} GB/s (2 cores together), so the "
               f"bandwidth ceiling for decode is {ceil_lo:.1f}-{ceil_hi:.1f} tok/s. "
               "Copy bandwidth counts reads and writes; read-only bandwidth may be higher.\n")
    out.append(md_table(s, ["ctx", "n_ctx", "threads", "prefill_tps", "decode_tps", "weight_gbs", "pct_bw"],
                        ["Context", "n_ctx", "Threads", "Prefill tok/s", "Decode tok/s",
                         "Weight read GB/s", "% of 2-core copy BW"],
                        [str, i0, i0, f2, f2, f2, lambda v: f"{v:.0f}%"]))

    with open(os.path.join(HERE, "results.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")

    # ---- Figure: the ledger gap ------------------------------------------
    INK, INK2, GRID = "#0b0b0b", "#52514e", "#e6e5e1"
    BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"
    plt.rcParams.update({"font.size": 10, "axes.edgecolor": INK2, "axes.labelcolor": INK,
                         "xtick.color": INK2, "ytick.color": INK2, "text.color": INK})
    fig, ax = plt.subplots(figsize=(8, 5), dpi=200)
    fig.patch.set_facecolor("#fcfcfb"); ax.set_facecolor("#fcfcfb")
    ax.axhline(BOARD_RAM_MIB, color=INK2, lw=1, ls=(0, (2, 2)))
    ax.text(alloc["n_ctx"].min(), BOARD_RAM_MIB + 25, f"Board RAM ({BOARD_RAM_MIB} MiB)", color=INK2, fontsize=9)
    ax.plot(a["n_ctx"], a["runtime_total_mib"], color=ORANGE, lw=2, marker="o", ms=6,
            label="llama.cpp reported total")
    ax.plot(a["n_ctx"], a["pred_vmhwm"], color=INK, lw=1.2, ls=(0, (4, 3)), zorder=5,
            label="Predicted peak (formula, 1 anchor run)")
    ax.plot(a["n_ctx"], a["vmhwm_mib"], color=BLUE, lw=2, marker="o", ms=6,
            label="OS-measured peak, short prompt")
    ax.plot(f["n_ctx"], f["vmhwm_mib"], color=AQUA, lw=2, marker="s", ms=6,
            label="OS-measured peak, ~90% full context")
    last = a.iloc[-1]
    ax.annotate("", xy=(last["n_ctx"], last["vmhwm_mib"] + 15), xytext=(last["n_ctx"], last["runtime_total_mib"] - 15),
                arrowprops=dict(arrowstyle="<->", color=INK2, lw=1))
    ax.text(last["n_ctx"] * 1.08, (last["vmhwm_mib"] + last["runtime_total_mib"]) / 2,
            f"{last['overstate']:.0f} MiB\nreported but\nnot resident\n(short prompt)",
            ha="left", va="center", fontsize=9, color=INK)
    ax.set_xscale("log", base=2)
    ax.set_xlim(100, a["n_ctx"].max() * 2.4)
    ax.set_xticks(a["n_ctx"]); ax.set_xticklabels([f"{int(x):,}" for x in a["n_ctx"]])
    ax.set_xlabel("Context length n_ctx (tokens)")
    ax.set_ylabel("Memory (MiB)")
    ax.set_ylim(0, BOARD_RAM_MIB * 1.08)
    ax.grid(axis="y", color=GRID, lw=0.8); ax.set_axisbelow(True)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    ax.set_title("Qwen2.5-0.5B (Q4_K_M) on the SL2610: runtime report vs. measured peak",
                 loc="left", fontsize=11, color=INK)
    ax.legend(frameon=False, loc="upper left", bbox_to_anchor=(0, 0.93), fontsize=9)
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "memory_ledger.png"), facecolor=fig.get_facecolor())
    print("wrote results.md and figures/memory_ledger.png")


if __name__ == "__main__":
    main()
